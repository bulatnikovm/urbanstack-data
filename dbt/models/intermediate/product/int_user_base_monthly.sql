-- Канонічна БАЗА користувачів по місяцях для продуктового домену.
-- Грануляція: user_id × report_month (ОДИН рядок на людину в місяці).
--
-- Тонка обгортка над спільним `int_user_exclusions` — уся логіка виключення
-- (співробітники / індивідуально деактивовані / деактивовані будинки,
-- point-in-time) живе там і переюзовується операційним доменом.
--
-- Що змінилось 2026-08-04 (рішення Микити):
--   * Грануляція БЕЗ complex_id — користувач рахується РІВНО ОДИН РАЗ навіть
--     якщо має приміщення в кількох ЖК («два особові рахунки = один
--     користувач»). Розріз по ЖК іде через `primary_complex_id`, тому сума по
--     ЖК тепер дорівнює тоталу. Раніше 1 660 людей рахувались двічі й більше.
--   * Будинок, деактивований 1 серпня, у серпні вже не рахується.
--
-- Це єдине джерело "потенційних"/"підтверджених" і для Стр.1, і для знаменника
-- STAR (Стр.4) — раніше методик було щонайменше три.

select
    report_month,
    user_id,
    user_phone_sk,
    role,
    primary_complex_id      as complex_id,
    primary_house_id        as house_id,
    user_created_month,

    is_employee,
    is_role_deactivated,
    is_house_deactivated,
    exclusion_reason,
    is_active_resident,
    is_confirmed,
    is_verified

from {{ ref('int_user_exclusions') }}
