{#
    Зрілість звітного місяця. Спільна логіка для детектора аномалій і журналу
    ревізій — щоб «поточний / недозрілий / устоявся» визначалось в одному місці.

    Підстава — вимір дозагрузки подій (docs/data_drift_findings.md §B):
    у EVENTS_407641 стабільно 3–5% подій місяця приходять ПІСЛЯ його кінця,
    вихід на ~99% — на 7-й день. Тобто:

      current      — місяць триває. Рівневі метрики занижені подвійно (і днів
                     менше, і навіть за минулі дні ще не все доїхало).
                     Порівнювати із закритими місяцями не можна ніколи.
      provisional  — місяць закрився менше 7 днів тому. Показує на 2-3% менше,
                     ніж покаже потім. Пороги множимо, але не глушимо повністю.
      settled      — устоявся, можна порівнювати як є.

    7 днів — не кругле число «на око», а точка виходу кривої на 98–99%
    (найгірший місяць у вибірці — березень, 97,2%).
#}

{% macro month_status(report_month_col) -%}
    case
        when {{ report_month_col }} = date_trunc(current_date(), month)
            then 'current'
        when date_diff(current_date(), last_day({{ report_month_col }}, month), day) <= 7
            then 'provisional'
        else 'settled'
    end
{%- endmacro %}


{#
    Смуга «нормального» ретроактивного дрейфу для вже закритого місяця, у
    частках від значення, на МІСЯЦЬ календарного часу.

    Виміряно на 13 щоденних зрізах (docs/data_drift_findings.md §A):
      crm    — count_potential −0,09% / count_confirmed +0,29% за 12 днів,
               тобто ~0,2–0,7%/міс. Беремо 1,5%/міс із запасом ×2.
      event  — подієві ряди заморожені (unique_users +0 за 12 днів), рухає їх
               тільки дозагрузка, і тільки вгору. 0,5%/міс вистачає.
      mixed  — числитель подієвий, знаменник CRM-ний. Такі ряди СИСТЕМАТИЧНО
               сповзають: star_rate_of_confirmed втратив 0,29% за 12 днів суто
               через знаменник. Найширша смуга.

    Все, що ВИЙШЛО за смугу, — це вже не механіка, а подія: масове зняття
    прив'язок, зміна ролей пачкою, перезалив spaces. Саме це й треба ловити.
#}

{% macro drift_band_pct_per_month(source_kind_col) -%}
    case {{ source_kind_col }}
        when 'crm'   then 0.015
        when 'event' then 0.005
        when 'mixed' then 0.020
        else 0.020
    end
{%- endmacro %}
