/**
 * Ролі й області видимості — чисті типи та правила, без жодного звернення
 * до бази.
 *
 * Окремий файл від `lib/access.ts` навмисно: той `server-only` (тримає
 * service_role-ключ Supabase), а ці правила потрібні і клієнтським
 * компонентам — формі в адмінці й сайдбару. Імпорт `access.ts` з клієнта
 * зламав би збірку, а дублювання списку ролей у двох місцях рано чи пізно
 * розійшлося б.
 */

/**
 * ОБЛАСТЬ ВИДИМОСТІ — те, ЩО показує сторінка, а не хто її дивиться.
 *
 * Проміжний шар між роллю і маршрутом зʼявився, коли знадобилось закрити
 * операційній команді не весь продуктовий дашборд цілком, а ще й дві
 * сторінки всередині операційного (запит Микити 2026-08-27). Без нього
 * правило доступу перетворювалось на список шляхів, який доводиться
 * памʼятати й доповнювати руками — рівно той механізм розсинхрону, який ми
 * викорчовували з хардкод-списків будинків.
 *
 * · `product`    — продуктовий дашборд (аудиторія, активація, STAR…).
 * · `operations` — щоденна операційна робота: заявки, SLA, CSAT, NPS.
 * · `insights`   — аналітика на ПЕРСОНАЛЬНИХ сигналах: ризик відтоку й
 *                  сегменти напруги. Технічно вона під `/operations`, але
 *                  за змістом це профілювання мешканців за текстами їхніх
 *                  звернень — внутрішній інструмент, не робочий екран
 *                  клієнтського сервісу.
 * · `admin`      — керування доступами.
 */
export type Scope = "product" | "operations" | "insights" | "admin";

/**
 * Три ролі.
 *
 * `operations` бачить ЛИШЕ щоденну операційку — клієнтський сервіс працює
 * із заявками, а продуктові метрики й профілювання мешканців лишаються
 * внутрішніми (запит Максима 2026-08-26, уточнений 2026-08-27).
 *
 * ⚠️ Список ролей дублюється CHECK-констрейнтом у Supabase
 * (`dashboard_users_role_check`). Нову роль треба додавати В ОБОХ місцях,
 * інакше вставка з адмінки впаде 400-ю з боку PostgREST.
 */
export type Role = "admin" | "viewer" | "operations";

const SCOPES_BY_ROLE: Record<Role, readonly Scope[]> = {
  admin: ["product", "operations", "insights", "admin"],
  viewer: ["product", "operations", "insights"],
  operations: ["operations"],
};

export const ROLE_LABELS: Record<Role, string> = {
  admin: "Адміністратор",
  viewer: "Перегляд",
  operations: "Тільки операційний",
};

/** Що саме бачить роль — текст для адмінки, щоб не гадати за назвою. */
export const ROLE_HINTS: Record<Role, string> = {
  admin: "Обидва дашборди + керування доступами",
  viewer: "Обидва дашборди, без керування доступами",
  operations: "Лише операційний: заявки, SLA, CSAT, NPS. Без продуктового, без ризику відтоку й сегментів",
};

export const isRole = (v: unknown): v is Role =>
  v === "admin" || v === "viewer" || v === "operations";

/**
 * Маршрут → область. Порядок ВАЖЛИВИЙ: перший збіг виграє, тому
 * найконкретніші префікси стоять вище за загальні.
 *
 * Останній рядок — `"/"` → `product`. Це не «решта продуктова», це
 * ЗАКРИТО ЗА ЗАМОВЧУВАННЯМ: будь-яка нова сторінка в корені автоматично
 * недоступна ролі `operations`, поки їй свідомо не призначили іншу область.
 * Помилитись можна лише в бік суворості.
 */
const ROUTE_SCOPES: ReadonlyArray<{ prefix: string; scope: Scope }> = [
  { prefix: "/admin", scope: "admin" },
  { prefix: "/operations/churn", scope: "insights" },
  { prefix: "/operations/segments", scope: "insights" },
  { prefix: "/operations", scope: "operations" },
  { prefix: "/", scope: "product" },
];

export function scopeForPath(pathname: string): Scope {
  const hit = ROUTE_SCOPES.find(
    (r) => pathname === r.prefix || pathname.startsWith(`${r.prefix}/`)
  );
  return hit?.scope ?? "product";
}

/**
 * Куди веде корінь дашборду для цієї ролі. Єдина точка правди — і проксі, і
 * сайдбар, і сторінка входу беруть звідси, щоб не розʼїхались.
 */
export const homeFor = (role: Role | undefined) =>
  role === "operations" ? "/operations" : "/";

/**
 * Чи має роль доступ до шляху.
 *
 * ⚠️ `undefined` трактується як `viewer`, і це НЕ дірка: неавторизованого
 * глядача відсікає проксі задовго до цієї перевірки, а авторизований завжди
 * має роль (`auth.config.ts` підставляє `viewer`, якщо в токені сміття).
 * Розділення обовʼязків тут таке: проксі відповідає на питання «чи ти
 * взагалі увійшов», `canSee` — на «що тобі видно». Якщо колись знадобиться
 * дефолт «нічого не видно», міняти треба разом із локальним переглядом:
 * без сесії дашборд стане суцільним 404.
 */
export function canSee(role: Role | undefined, pathname: string): boolean {
  const scopes = SCOPES_BY_ROLE[role ?? "viewer"] ?? SCOPES_BY_ROLE.viewer;
  return scopes.includes(scopeForPath(pathname));
}
