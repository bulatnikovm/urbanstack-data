import "server-only";

import { notFound } from "next/navigation";

import { auth } from "@/auth";
import { canSee } from "@/lib/roles";

/**
 * Друга лінія захисту сторінки — після проксі.
 *
 * Проксі вже редіректить людину без доступу на її дашборд, і в браузері
 * вона сюди не потрапить. Але RSC-ендпоінт сторінки можна смикнути напряму,
 * і тоді проксі — не єдине, що стоїть між людиною й даними.
 *
 * `notFound()`, а не редірект: сторінки, якої тобі не видно, для тебе не
 * існує — і сам факт її наявності теж не інформація.
 *
 * ⚠️ Шлях передається РЯДКОМ, а не береться з рантайму: серверний компонент
 * свого маршруту не знає. Якщо сторінку переносять — рядок тут треба
 * поправити разом із текою. Дешева ціна за те, що правило доступу лишається
 * одне на весь застосунок (`canSee` + `ROUTE_SCOPES` у lib/roles.ts).
 */
export async function requireAccess(pathname: string) {
  const session = await auth();
  if (!canSee(session?.user?.role, pathname)) notFound();
}
