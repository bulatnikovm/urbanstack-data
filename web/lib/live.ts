/**
 * Живі курсори: хто зараз у дашборді й де його миша.
 *
 * ── Що це й для кого ──────────────────────────────────────────────────────
 * Приколюха на прохання Микити (2026-08-31), і видно її ТІЛЬКИ йому:
 * решта нічого не бачить — ні аватарок, ні курсорів. Список тих, кому
 * видно, живе в env (`LIVE_WATCHERS`), а не в коді, щоб додати собі другий
 * акаунт можна було без релізу.
 *
 * ⚠️ Рішення «кому видно» приймається на СЕРВЕРІ (layout читає сесію) і
 * приїжджає в компонент пропом. Клієнтська перевірка тут не годиться: її
 * видно в DevTools і перемикається за секунду.
 *
 * ⚠️ І окремо, щоб не було ілюзій: це обмеження ІНТЕРФЕЙСУ, а не захист.
 * Anon-ключ Supabase лежить у бандлі, тож технічно до каналу може
 * підключитись будь-хто, кому не лінь відкрити DevTools. Політика на
 * каналі відповідає на питання «хто взагалі може підключитись», а не «хто
 * що бачить».
 *
 * ── Трафік ────────────────────────────────────────────────────────────────
 * На безкоштовному Supabase ліміт — 2 млн повідомлень на місяць, а миша
 * рухається 60 разів на секунду. Тому діють одразу три обмежувачі:
 * тротлінг до ~10 повідомлень на секунду, пауза коли вкладка неактивна, і
 * головне — НІХТО не шле координати, поки в каналі немає спостерігача
 * (див. `watch` у presence). Микити немає на сторінці — потоку немає
 * взагалі, і чужі позиції не залишають чужих браузерів.
 */

/** Скільки разів на секунду шлемо позицію (при русі миші). */
export const CURSOR_HZ = 10;

/** Через скільки мовчання курсор гасне, мс. */
export const CURSOR_IDLE_MS = 10_000;

export type LiveUser = {
  email: string;
  name: string;
  image: string | null;
};

/** Присутність у каналі: хто тут і чи дивиться він курсори. */
export type LivePeer = LiveUser & {
  /** Спостерігач — той, кому курсори видно. Іншим це прапорець «є кому
   *  показувати», тобто дозвіл почати слати свої координати. */
  watch: boolean;
};

/**
 * ⚠️ «Активний / не активний» рахується НЕ з presence, а з часу останнього
 * повідомлення про курсор, і це не дрібниця. Presence — це стан, який при
 * кожній зміні розсилається всім підписникам; писати туди «востаннє
 * ворухнув мишею» означало б робити те саме, від чого ми пішли на
 * broadcast. Тому мітку часу ставить ОТРИМУВАЧ у себе локально.
 */

/** Позиція курсора в системі координат КОНТЕНТУ, не вікна (див. нижче). */
export type CursorPoint = {
  email: string;
  /** Частка ширини `<main>`: 0 — лівий край, 1 — правий. */
  x: number;
  /** Пікселі від верху `<main>`, незалежно від прокрутки. */
  y: number;
};

/**
 * Хто бачить курсори. Порожній список — не бачить ніхто, і це навмисний
 * дефолт: без явного налаштування фіча просто не існує.
 */
export function liveWatchers(): string[] {
  return (process.env.LIVE_WATCHERS ?? "")
    .split(",")
    .map((s) => s.trim().toLowerCase())
    .filter(Boolean);
}

export const isWatcher = (email: string | null | undefined) =>
  !!email && liveWatchers().includes(email.trim().toLowerCase());

/**
 * Канал — на СТОРІНКУ, а не на весь дашборд: курсор має сенс лише серед
 * тих, хто дивиться те саме. Хто на якій сторінці — і так видно в
 * списку присутніх.
 */
export const liveChannel = (pathname: string) => `cursors:${pathname}`;

/**
 * Колір людини — з пошти, а не з лічильника підключень: інакше та сама
 * людина сьогодні синя, завтра зелена, і звичка «жовтий — це Максим» не
 * встигає утворитись.
 *
 * Відтінки беруться з кола рівномірно, насиченість і світлота фіксовані —
 * так будь-який колір лишається читабельним підписом на світлій і темній
 * темі.
 */
export function liveColor(email: string): string {
  let hash = 0;
  for (let i = 0; i < email.length; i++) {
    hash = (hash * 31 + email.charCodeAt(i)) >>> 0;
  }
  return `oklch(0.62 0.17 ${hash % 360})`;
}

/** Ім'я для підпису: у Google-акаунтах воно є завжди, пошта — запасний варіант. */
export const liveLabel = (u: { name?: string | null; email: string }) =>
  u.name?.trim() || u.email.split("@")[0];
