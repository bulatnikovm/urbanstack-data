import "server-only";

import { auth } from "@/auth";

/**
 * Експериментальні функції — видно лише тим, кого перелічили в LAB_EMAILS.
 *
 * Це НЕ третя вісь доступу поруч із роллю й областю (`lib/roles.ts`). Ті дві
 * описують постійну структуру дашборду й редагуються людиною в адмінці; ця
 * перевірка — тимчасовий вимикач на час, поки функція обкатується на одному
 * глядачеві. Заводити під неї область означало б додати `Scope`, CHECK у
 * Supabase і галочку у формі — і потім усе це прибирати, коли функція
 * доїде до всіх. Змінна середовища знімається одним рядком.
 *
 * ⚠️ Наслідок: список НЕ редагується з інтерфейсу. Додати людину — це
 * правка змінної у Vercel і редеплой. Саме тому це вимикач на обкатку, а не
 * механізм видачі доступів.
 *
 * ── Два стани, і кожен відповідає на своє питання ─────────────────────────
 *
 * СЕСІЇ НЕМАЄ — це локальний перегляд. У продакшні на кожну сторінку
 * дивиться проксі, і без сесії людина сюди не дійде; тому відсутність сесії
 * означає «запущено локально», і функцію видно. Та сама логіка, що в
 * `requireAccess` (`lib/guard.ts`): «чи ти увійшов» — питання проксі, а не
 * цього файлу. Без цієї гілки локальний перегляд показував би порожнечу
 * замість функції, яку саме зараз і робимо.
 *
 * СЕСІЯ Є — працює строгий список, і порожній LAB_EMAILS означає «нікому».
 * Fail-closed навмисно: забута змінна має ховати функцію, а не показувати
 * її всім. Протилежний дефолт уже коштував нам відкритого дашборду
 * (`proxy.ts.OFF-for-local-view`, CLAUDE.md §8г).
 *
 * ⚠️ Саме гілкою «сесії немає» це відрізняється від `isWatcher` у
 * `lib/live.ts` — там без сесії теж нічого не видно, і це правильно: курсори
 * без залогінених людей не мають сенсу. Тут інакше, бо наратив — частина
 * сторінки, яку локально й розробляють.
 *
 * ⚠️ Тут ПОШТА, а не людина: після переїзду на корпоративний вхід (ANA-17)
 * та сама людина заходить під іншою адресою, і функція мовчки зникне —
 * жодної помилки не буде. Та сама пастка, що в LIVE_WATCHERS.
 */
export function labEmails(): string[] {
  return (process.env.LAB_EMAILS ?? "")
    .split(",")
    .map((s) => s.trim().toLowerCase())
    .filter(Boolean);
}

export async function inLab(): Promise<boolean> {
  const session = await auth();
  const email = session?.user?.email?.trim().toLowerCase();
  if (!email) return true;
  return labEmails().includes(email);
}
