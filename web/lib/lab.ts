import "server-only";

import { auth } from "@/auth";

/**
 * Блок, який ще обкатується, — видно лише адміну.
 *
 * Це внутрішньосторінковий близнюк області `drafts`: та ховає ЦІЛУ сторінку
 * (`/adoption`), а тут ховати нічого — наратив живе всередині пʼяти вже
 * відкритих сторінок, і власної області під нього не заведеш. Підстава та
 * сама: показник, який побачили раз і запамʼятали неправильно, потім живе
 * своїм життям.
 *
 * ⚠️ Спершу тут був список пошт (`LAB_EMAILS`), і він виявився хибним рівно
 * так, як і було записано в цьому файлі з першого дня: після ANA-17 та сама
 * людина заходить через корпоративний M365 під ІНШОЮ адресою, блок мовчки
 * зникає, і жодного сліду ні в інтерфейсі, ні в логах. Роль переживає зміну
 * входу, бо вона прикріплена до запису в `dashboard_users`, а не до способу
 * автентифікації.
 *
 * ⚠️ Наслідок, який треба пам'ятати: зʼявиться другий адмін — побачить і він.
 * Для «лише конкретна людина» ролі замало, але такої вимоги немає: адмін
 * зараз один, і саме він обкатує.
 *
 * ⚠️ СЕСІЇ НЕМАЄ — це локальний перегляд, і блок видно. У продакшні на кожну
 * сторінку дивиться проксі, тож без сесії людина сюди не дійде; питання «чи
 * ти увійшов» — його, а не наше. Та сама розв'язка, що в `requireAccess`
 * (`lib/guard.ts`): без цієї гілки локальний перегляд, де логіну немає
 * взагалі, показував би порожнечу замість функції, яку саме зараз і роблять.
 */
export async function inLab(): Promise<boolean> {
  const session = await auth();
  if (!session?.user) return true;
  return session.user.role === "admin";
}
